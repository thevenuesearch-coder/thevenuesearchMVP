/**
 * Loads the verified amenities & services in
 * scripts/venue-features-data.mjs into Supabase (venue_features).
 *
 * Safe to re-run: upserts on (venue_id, feature_key).
 *
 * Requires supabase/migration_venue_features.sql to be applied and
 * NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY in .env.local.
 *
 * Usage:
 *   npm run seed:features            upsert into Supabase
 *   npm run seed:features -- --sql   write supabase/seed_venue_features.sql
 *                                    (paste into the Supabase SQL editor)
 *   npm run seed:features -- --json  write lib/compare/verified-features.json
 *                                    (bundled fallback the app uses until the
 *                                    database has rows for a venue)
 *   npm run seed:features -- --check validate the data file only
 *
 * Validation (always runs): known feature_key, https source_url,
 * valid source_type, ISO verified_at, no duplicates per venue.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { venueFeaturesData } from './venue-features-data.mjs';

const registry = JSON.parse(
  readFileSync(new URL('../lib/compare/features.json', import.meta.url), 'utf8')
);
const KEYS = new Set(registry.map((d) => d.key));
const SOURCE_TYPES = new Set(['official', 'google', 'authoritative']);

/* ---------- flatten + validate ---------- */
const rows = [];
const problems = [];

for (const venue of venueFeaturesData) {
  const seen = new Set();

  for (const source of venue.sources) {
    if (!/^https?:\/\//i.test(source.sourceUrl || '')) {
      problems.push(`${venue.slug}: bad sourceUrl "${source.sourceUrl}"`);
    }
    if (!SOURCE_TYPES.has(source.sourceType)) {
      problems.push(`${venue.slug}: bad sourceType "${source.sourceType}"`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(source.verifiedAt || '')) {
      problems.push(`${venue.slug}: bad verifiedAt "${source.verifiedAt}"`);
    }

    for (const [key, evidence, detail] of source.features) {
      if (!KEYS.has(key)) {
        problems.push(`${venue.slug}: unknown feature_key "${key}"`);
        continue;
      }
      if (seen.has(key)) {
        problems.push(`${venue.slug}: duplicate feature_key "${key}"`);
        continue;
      }
      if (!evidence) {
        problems.push(`${venue.slug}/${key}: missing evidence note`);
        continue;
      }
      seen.add(key);
      rows.push({
        slug: venue.slug,
        feature_key: key,
        detail: detail ?? null,
        source_url: source.sourceUrl,
        source_type: source.sourceType,
        verified_at: source.verifiedAt,
        source_note: evidence,
        status: 'published',
      });
    }
  }
}

if (problems.length) {
  console.error('\nInvalid venue-features data:\n - ' + problems.join('\n - '));
  process.exit(1);
}

const args = new Set(process.argv.slice(2));
console.log(
  `Validated ${rows.length} verified facts across ${
    new Set(rows.map((r) => r.slug)).size
  } venues (${venueFeaturesData.length - new Set(rows.map((r) => r.slug)).size} with none yet).`
);

if (args.has('--check')) process.exit(0);

/* ---------- --json: bundled fallback used by the app ---------- */
if (args.has('--json')) {
  const bySlug = {};
  for (const r of rows) {
    (bySlug[r.slug] ??= []).push({
      key: r.feature_key,
      detail: r.detail,
      sourceUrl: r.source_url,
      sourceType: r.source_type,
      verifiedAt: r.verified_at,
    });
  }
  writeFileSync(
    new URL('../lib/compare/verified-features.json', import.meta.url),
    JSON.stringify(bySlug, null, 2) + '\n'
  );
  console.log('Wrote lib/compare/verified-features.json');
  process.exit(0);
}

/* ---------- --sql: generate an editor-ready file ---------- */
if (args.has('--sql')) {
  const q = (v) => (v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
  const lines = [
    '-- GENERATED by `npm run seed:features -- --sql` from',
    '-- scripts/venue-features-data.mjs. Do not edit by hand.',
    '-- Requires supabase/migration_venue_features.sql. Safe to re-run.',
    '',
    'insert into public.venue_features',
    '  (venue_id, feature_key, detail, source_url, source_type, verified_at, source_note, status)',
    'select v.id, d.feature_key, d.detail, d.source_url, d.source_type, d.verified_at::date, d.source_note, d.status',
    'from (values',
    rows
      .map(
        (r) =>
          `  (${q(r.slug)}, ${q(r.feature_key)}, ${q(r.detail)}, ${q(r.source_url)}, ${q(
            r.source_type
          )}, ${q(r.verified_at)}, ${q(r.source_note)}, ${q(r.status)})`
      )
      .join(',\n'),
    ') as d(slug, feature_key, detail, source_url, source_type, verified_at, source_note, status)',
    'join public.venues v on v.slug = d.slug',
    'on conflict (venue_id, feature_key) do update set',
    '  detail = excluded.detail,',
    '  source_url = excluded.source_url,',
    '  source_type = excluded.source_type,',
    '  verified_at = excluded.verified_at,',
    '  source_note = excluded.source_note,',
    '  status = excluded.status,',
    '  updated_at = now();',
    '',
  ];
  writeFileSync(
    new URL('../supabase/seed_venue_features.sql', import.meta.url),
    lines.join('\n')
  );
  console.log('Wrote supabase/seed_venue_features.sql');
  process.exit(0);
}

/* ---------- default: upsert via service role ---------- */
function loadEnvLocal() {
  if (!existsSync('.env.local')) return;
  for (const line of readFileSync('.env.local', 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    if (i === -1) continue;
    const key = t.slice(0, i).trim();
    let value = t.slice(i + 1).trim();
    if (/^(".*"|'.*')$/.test(value)) value = value.slice(1, -1);
    if (!(key in process.env)) process.env[key] = value;
  }
}
loadEnvLocal();

const { createClient } = await import('@supabase/supabase-js');
const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!url || !key) {
  console.error(
    '\nMissing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local.\n'
  );
  process.exit(1);
}

const supabase = createClient(url, key, {
  auth: { autoRefreshToken: false, persistSession: false },
});

const slugs = [...new Set(rows.map((r) => r.slug))];
const { data: venues, error } = await supabase
  .from('venues')
  .select('id, slug')
  .in('slug', slugs);

if (error) {
  console.error('Could not read venues:', error.message);
  process.exit(1);
}

const idBySlug = new Map(venues.map((v) => [v.slug, v.id]));
const missing = slugs.filter((s) => !idBySlug.has(s));
if (missing.length) {
  console.warn(`Skipping venues not found in the database: ${missing.join(', ')}`);
}

const payload = rows
  .filter((r) => idBySlug.has(r.slug))
  .map(({ slug, ...rest }) => ({ venue_id: idBySlug.get(slug), ...rest }));

const { error: upsertError } = await supabase
  .from('venue_features')
  .upsert(payload, { onConflict: 'venue_id,feature_key' });

if (upsertError) {
  console.error('Upsert failed:', upsertError.message);
  process.exit(1);
}

console.log(`Upserted ${payload.length} venue_features rows.`);
